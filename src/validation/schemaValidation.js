// ─── Structural check ───────────────────────────────────────────────────────

// [{ kind: 'unknownElement', element } | { kind: 'notAllowed', element, parent }
//  | { kind: 'unknownAttribute', attribute, element } | { kind: 'wrongRoot', element, expected }]
// against one schema's structure. Prefixed attributes other than xlink:* and
// namespace declarations are not schema vocabulary and are left out.
export function checkExampleStructure(doc, structure) {
  const elements = structure.elements;
  const problems = [];
  const seen = new Set();
  const add = (problem) => {
    const key = JSON.stringify(problem);
    if (!seen.has(key)) {
      seen.add(key);
      problems.push(problem);
    }
  };
  const root = doc.documentElement;
  if (structure.skeleton && root.nodeName !== structure.skeleton.root) {
    add({ kind: 'wrongRoot', element: root.nodeName, expected: structure.skeleton.root });
  }
  const walk = (el, parentName) => {
    const name = el.nodeName;
    const known = Boolean(elements[name]);
    if (!known) add({ kind: 'unknownElement', element: name });
    else if (parentName && elements[parentName] && !elements[parentName].children.includes(name)) {
      add({ kind: 'notAllowed', element: name, parent: parentName });
    }
    if (known) {
      for (const a of Array.from(el.attributes || [])) {
        if (a.name === 'xmlns' || a.name.startsWith('xmlns:') || a.name.startsWith('xsi:')) continue;
        if (a.name.includes(':') && !a.name.startsWith('xlink:')) continue;
        const local = a.name.replace(/^xlink:/, '');
        if (!elements[name].attributes.includes(local)) add({ kind: 'unknownAttribute', attribute: a.name, element: name });
      }
    }
    for (let n = el.firstChild; n; n = n.nextSibling) if (n.nodeType === 1) walk(n, name);
  };
  walk(root, null);
  return problems;
}

// ─── CALS table spans (C3, Part 1b) ────────────────────────────────────────

// CALS tables (S1000D and DITA use the same model): an <entry
// morerows="N"> also occupies its column(s) in the next N rows of its
// thead/tbody/tfoot, so those rows must not have an entry of their own
// there. An LLM writing examples often adds one anyway. The schema
// structure cannot see this (every element is allowed where it is), so it
// is checked here:
//   { kind: 'spannedEntry', row, column }   -- row N has an entry in a
//                                             column spanned from above
//   { kind: 'morerowsPastEnd', row, column } -- the span of row N's entry
//                                             runs past the last row
//   { kind: 'rowFullyCovered', row }        -- every entry of row N sits in
//                                             a spanned column (or the row
//                                             has none and is fully spanned):
//                                             removing them would leave an
//                                             empty <row>, so this replaces
//                                             the row's spannedEntry problems
//   { kind: 'emptyRow', row }               -- row N has no <entry> and
//                                             is not fully covered from
//                                             above (CALS needs at least one)
// `row` is 1-based within its thead/tbody/tfoot; `column` is the colspec's
// colname, or c1, c2… by position when the table has no colspecs.
// Columns come from @colname / @namest–@nameend when the entry has them
// (checked against the spans directly), otherwise by position: an entry
// without a name takes the next column in reading order, ignoring spans the
// way a writer who forgot them would -- so, when a row has more entries than
// its free columns, the entries sitting in spanned columns are the extra
// ones. Never throws: an unknown colname is treated as positional.
export function checkCalsTableSpans(doc) {
  return calsSpanProblems(doc).map(({ entry, ...problem }) => problem);
}

// Same walk, keeping the offending <entry> of each spannedEntry problem.
function calsSpanProblems(doc) {
  const problems = [];
  const childrenNamed = (el, name) => Array.from(el.childNodes || []).filter((n) => n.nodeType === 1 && n.nodeName === name);
  const intAttr = (el, name) => {
    const n = Number.parseInt(el.getAttribute(name) || '', 10);
    return Number.isFinite(n) && n > 0 ? n : 0;
  };
  const tgroups = Array.from(doc.getElementsByTagName('tgroup'));
  for (const tgroup of tgroups) {
    const colspecs = childrenNamed(tgroup, 'colspec');
    const colIndex = new Map();
    colspecs.forEach((c, i) => {
      const name = c.getAttribute('colname');
      if (name && !colIndex.has(name)) colIndex.set(name, i);
    });
    const label = (i) => colspecs[i]?.getAttribute('colname') || `c${i + 1}`;
    for (const sectionName of ['thead', 'tbody', 'tfoot']) {
      for (const section of childrenNamed(tgroup, sectionName)) {
        const rows = childrenNamed(section, 'row');
        const declared = intAttr(tgroup, 'cols') || colspecs.length;
        // Without @cols or colspecs, the first row (nothing spans into it)
        // gives the width.
        const cols = declared || (rows[0] ? childrenNamed(rows[0], 'entry').length : 0);
        const spanned = rows.map(() => new Set());
        rows.forEach((row, r) => {
          const entries = childrenNamed(row, 'entry');
          const named = (entry) => {
            const start = colIndex.get(entry.getAttribute('colname') || entry.getAttribute('namest'));
            if (start === undefined) return null;
            const end = colIndex.get(entry.getAttribute('nameend'));
            return { start, end: end !== undefined && end >= start ? end : start };
          };
          const free = cols - spanned[r].size;
          const overfull = entries.length > free;
          const rowProblems = [];
          let cursor = 0;
          entries.forEach((entry, e) => {
            let span = named(entry);
            if (!span) {
              if (overfull) {
                // Position as written: entry e sits in column e.
                span = { start: e, end: e };
              } else {
                while (spanned[r].has(cursor)) cursor += 1;
                span = { start: cursor, end: cursor };
              }
            }
            cursor = span.end + 1;
            for (let c = span.start; c <= span.end; c += 1) {
              if (spanned[r].has(c)) {
                rowProblems.push({ kind: 'spannedEntry', row: r + 1, column: label(c), entry });
                break;
              }
            }
            const more = intAttr(entry, 'morerows');
            for (let k = 1; k <= more; k += 1) {
              if (r + k >= rows.length) {
                rowProblems.push({ kind: 'morerowsPastEnd', row: r + 1, column: label(span.start) });
                break;
              }
              for (let c = span.start; c <= span.end; c += 1) spanned[r + k].add(c);
            }
          });
          const spannedCount = rowProblems.filter((p) => p.kind === 'spannedEntry').length;
          const fullyCovered = entries.length > 0 ? spannedCount === entries.length : cols > 0 && spanned[r].size >= cols;
          if (fullyCovered) {
            problems.push({ kind: 'rowFullyCovered', row: r + 1 }, ...rowProblems.filter((p) => p.kind !== 'spannedEntry'));
          } else if (entries.length === 0) {
            problems.push({ kind: 'emptyRow', row: r + 1 });
          } else {
            problems.push(...rowProblems);
          }
        });
      }
    }
  }
  return problems;
}

// C3b: an <entry> in a column a morerows above already covers is always an
// error, and the fix is always the same -- remove that entry. The
// application does it itself, on the LLM's content, before any correction
// round (a real run, titled-context at 297df74, sent two such tables back
// to the LLM and got them back unchanged). `content` is the example's
// content (one or several root elements); the entries are removed from the
// TEXT, so the rest stays exactly as written. Repeats until no entry sits
// in a spanned column (removing one can shift the next row's reading),
// then returns { content, removedRows: [row numbers, in order] }. Content
// that does not parse is returned unchanged -- its validation reports it.
// morerows running past the last row is not touched: that one has no
// single right fix and still goes to the LLM. Neither is an example with a
// row entirely covered from above (rowFullyCovered): removing its entries
// would leave an empty <row>, so nothing in that example is adjusted and
// the problem goes to the correction round.
const TAG_TOKEN_RE = /<!--[\s\S]*?-->|<!\[CDATA\[[\s\S]*?\]\]>|<\?[\s\S]*?\?>|<(\/?)([A-Za-z_][\w.:-]*)((?:\s+[^\s=/>]+\s*=\s*(?:"[^"]*"|'[^']*'))*)\s*(\/?)>/g;

// [start, end) of the Nth <entry> element (0-based, document order) in text.
function entrySpans(text) {
  const spans = [];
  const open = [];
  for (const m of text.matchAll(TAG_TOKEN_RE)) {
    if (m[2] === undefined || m[2] !== 'entry') continue;
    if (m[1]) {
      const index = open.pop();
      if (index !== undefined) spans[index].end = m.index + m[0].length;
    } else if (m[4]) {
      spans.push({ start: m.index, end: m.index + m[0].length });
    } else {
      open.push(spans.length);
      spans.push({ start: m.index, end: null });
    }
  }
  return spans;
}

export function removeSpannedCalsEntries(content, parseXml) {
  const original = String(content ?? '');
  let text = original;
  const removedRows = [];
  for (let pass = 0; pass < 10; pass += 1) {
    let doc;
    try {
      doc = parseXml(wrapRuleXmlFragment(text));
      if (!doc?.documentElement) break;
    } catch {
      break;
    }
    const problems = calsSpanProblems(doc);
    if (problems.some((p) => p.kind === 'rowFullyCovered')) return { content: original, removedRows: [] };
    const offending = problems.filter((p) => p.kind === 'spannedEntry');
    if (offending.length === 0) break;
    const allEntries = Array.from(doc.getElementsByTagName('entry'));
    const spans = entrySpans(text);
    if (spans.length !== allEntries.length) break; // text and DOM disagree: leave it
    const cuts = [];
    for (const p of offending) {
      const span = spans[allEntries.indexOf(p.entry)];
      if (!span || span.end === null) continue;
      let start = span.start;
      // Take the entry's own indentation (and line) with it.
      while (start > 0 && (text[start - 1] === ' ' || text[start - 1] === '\t')) start -= 1;
      if (start > 0 && text[start - 1] === '\n') start -= 1;
      cuts.push({ start, end: span.end });
      removedRows.push(p.row);
    }
    if (cuts.length === 0) break;
    // An entry inside another removed entry goes with it.
    const outer = cuts.filter((c) => !cuts.some((o) => o !== c && o.start <= c.start && c.end <= o.end));
    for (const cut of outer.sort((a, b) => b.start - a.start)) text = text.slice(0, cut.start) + text.slice(cut.end);
  }
  return { content: text, removedRows };
}

// ─── Missing CALS colspecs (C3b follow-up) ─────────────────────────────────
// An <entry colname="c2"> only means something if its <tgroup> has a
// <colspec colname="c2"/>; an LLM often writes the colnames and no colspec
// at all (the EXT-00001 run of 29/09: every table used c1/c2/c3 with no
// <colspec>). Like the morerows fix, the application adds them itself when
// the fix is unambiguous: one <colspec> per colname used (@colname, @namest,
// @nameend of the tgroup's own entries) that has none, placed in column
// order at the start of the <tgroup>, among the colspecs already there
// (never touched). A name's column comes from its number: c3, col3,
// column3, col-3 or a bare 3 are column 3 (the only forms read -- a name
// like "part" gives no column). Existing colspecs keep their CALS column
// (@colnum, or the previous one + 1). A new colspec gets @colnum only when
// its column does not follow the previous one (a gap), so c1/c2/c3 get the
// plain <colspec colname="cX"/>.
// Not adjusted -- the example goes to the correction round with the reason:
//   { kind: 'unorderableColname', colname } -- no column can be worked out
//                        (no number, column 0, or a column already taken
//                        by another colspec or colname)
//   { kind: 'tooManyColumns', columns, cols } -- the tgroup uses more
//                        distinct columns (or a higher column) than its @cols
// Either problem anywhere in the example leaves the whole example as
// written (same as rowFullyCovered for morerows).
const COLNAME_POSITION_RE = /^(?:c|col|column)?[-_]?(\d+)$/i;

function calsColspecPlans(doc) {
  const childrenNamed = (el, name) => Array.from(el.childNodes || []).filter((n) => n.nodeType === 1 && n.nodeName === name);
  const allColspecs = Array.from(doc.getElementsByTagName('colspec'));
  return Array.from(doc.getElementsByTagName('tgroup')).map((tgroup) => {
    const problems = [];
    const existing = [];
    let prev = 0;
    for (const c of childrenNamed(tgroup, 'colspec')) {
      const colnum = Number.parseInt(c.getAttribute('colnum') || '', 10);
      const position = Number.isFinite(colnum) && colnum > 0 ? colnum : prev + 1;
      prev = position;
      existing.push({ name: c.getAttribute('colname') || '', position, index: allColspecs.indexOf(c) });
    }
    const declared = new Set(existing.map((c) => c.name).filter(Boolean));
    const used = [];
    for (const section of ['thead', 'tbody', 'tfoot'].flatMap((n) => childrenNamed(tgroup, n))) {
      for (const row of childrenNamed(section, 'row')) {
        for (const entry of childrenNamed(row, 'entry')) {
          for (const attr of ['colname', 'namest', 'nameend']) {
            const name = entry.getAttribute(attr);
            if (name && !used.includes(name)) used.push(name);
          }
        }
      }
    }
    const taken = new Set(existing.map((c) => c.position));
    const missing = [];
    for (const name of used.filter((n) => !declared.has(n))) {
      const m = COLNAME_POSITION_RE.exec(name);
      const position = m ? Number.parseInt(m[1], 10) : 0;
      if (!position || taken.has(position)) {
        problems.push({ kind: 'unorderableColname', colname: name });
        continue;
      }
      taken.add(position);
      missing.push({ name, position });
    }
    const cols = Number.parseInt(tgroup.getAttribute('cols') || '', 10);
    if (Number.isFinite(cols) && cols > 0) {
      const distinct = new Set([...existing.map((c) => c.name || `#${c.position}`), ...used]).size;
      const columns = Math.max(distinct, ...existing.map((c) => c.position), ...missing.map((c) => c.position), 0);
      if (columns > cols) problems.push({ kind: 'tooManyColumns', columns, cols });
    }
    missing.sort((a, b) => a.position - b.position);
    return { tgroup, existing, missing, problems };
  });
}

// Problems the application cannot fix itself (see above); reported by
// validateExample so they reach the correction round.
export function checkCalsColspecs(doc) {
  return calsColspecPlans(doc).flatMap((plan) => plan.problems);
}

// [start, end) of every <name> element (document order) in text; end is
// null for an unclosed one.
function elementSpans(text, name) {
  const spans = [];
  const open = [];
  for (const m of text.matchAll(TAG_TOKEN_RE)) {
    if (m[2] === undefined || m[2] !== name) continue;
    if (m[1]) {
      const index = open.pop();
      if (index !== undefined) spans[index].end = m.index + m[0].length;
    } else if (m[4]) {
      spans.push({ start: m.index, end: m.index + m[0].length, openEnd: m.index + m[0].length });
    } else {
      open.push(spans.length);
      spans.push({ start: m.index, end: null, openEnd: m.index + m[0].length });
    }
  }
  return spans;
}

// Adds the missing colspecs to the TEXT of `content` (the rest stays exactly
// as written) → { content, added }. Unchanged (added 0) when nothing is
// missing, when any tgroup has an unfixable problem, or when the content
// does not parse or its text and DOM disagree.
export function addMissingCalsColspecs(content, parseXml) {
  const original = String(content ?? '');
  let doc;
  try {
    doc = parseXml(wrapRuleXmlFragment(original));
    if (!doc?.documentElement) return { content: original, added: 0 };
  } catch {
    return { content: original, added: 0 };
  }
  const plans = calsColspecPlans(doc);
  if (plans.some((p) => p.problems.length > 0)) return { content: original, added: 0 };
  if (!plans.some((p) => p.missing.length > 0)) return { content: original, added: 0 };
  const tgroupSpans = elementSpans(original, 'tgroup');
  const colspecSpans = elementSpans(original, 'colspec');
  if (tgroupSpans.length !== plans.length || colspecSpans.length !== doc.getElementsByTagName('colspec').length) {
    return { content: original, added: 0 };
  }
  const inserts = [];
  let added = 0;
  plans.forEach((plan, t) => {
    if (plan.missing.length === 0) return;
    const openEnd = tgroupSpans[t].openEnd;
    const lineBreak = /^\r?\n([ \t]*)/.exec(original.slice(openEnd));
    const format = (tag) => (lineBreak ? `\n${lineBreak[1]}${tag}` : tag);
    // Final order: existing and new colspecs by column; a new one goes after
    // the tgroup's open tag or after the existing colspec before it.
    const byAnchor = new Map();
    let prevPosition = 0;
    let anchor = openEnd;
    const sequence = [...plan.existing.map((c) => ({ ...c, existing: true })), ...plan.missing].sort((a, b) => a.position - b.position);
    for (const col of sequence) {
      if (col.existing) {
        const span = colspecSpans[col.index];
        if (!span || span.end === null) return;
        anchor = span.end;
      } else {
        const colnum = col.position === prevPosition + 1 ? '' : ` colnum="${col.position}"`;
        const list = byAnchor.get(anchor) || [];
        list.push(format(`<colspec colname="${col.name}"${colnum}/>`));
        byAnchor.set(anchor, list);
        added += 1;
      }
      prevPosition = col.position;
    }
    for (const [at, tags] of byAnchor) inserts.push({ at, text: tags.join('') });
  });
  let text = original;
  for (const ins of inserts.sort((a, b) => b.at - a.at)) text = text.slice(0, ins.at) + ins.text + text.slice(ins.at);
  return { content: text, added };
}

// English, for the correction request sent back to the LLM (the panel
// translates the same problems through i18n).
export function formatStructureProblem(problem, schema) {
  switch (problem.kind) {
    case 'spannedEntry':
      return `row ${problem.row}: column ${problem.column} is already spanned by the entry above (morerows); remove this entry`;
    case 'morerowsPastEnd':
      return `row ${problem.row}: morerows spans past the last row (column ${problem.column})`;
    case 'emptyRow':
      return `row ${problem.row} has no entry`;
    case 'rowFullyCovered':
      return `row ${problem.row} is entirely covered by morerows from above: give row ${problem.row} its own entries or lower the morerows`;
    case 'unorderableColname':
      return `colname="${problem.colname}" has no <colspec> and its column cannot be worked out: add <colspec colname="${problem.colname}"/> to the <tgroup>, in column order`;
    case 'tooManyColumns':
      return `the table uses ${problem.columns} columns but its <tgroup> says cols="${problem.cols}": use at most ${problem.cols} columns or raise cols`;
    case 'unknownElement':
      return `<${problem.element}> does not exist in the ${schema} schema`;
    case 'notAllowed':
      return `<${problem.element}> is not allowed inside <${problem.parent}>`;
    case 'unknownAttribute':
      return `@${problem.attribute} does not exist on <${problem.element}>`;
    case 'wrongRoot':
      return `the root element is <${problem.element}>, not <${problem.expected}>`;
    default:
      return String(problem.kind);
  }
}

// ═══ 5. XPath syntax ═══════════════════════════════════════════════════════

// Suggest Rule validation -- XPath syntax (schema-location encargo, Part 3).
// A real Mistral run wrote <objectPath>//&lt;emphasis&gt;</objectPath>: the
// name check (ruleNameCheck.js) extracts "emphasis", which IS a real 4.2
// element, so nothing was flagged -- the expression itself is not XPath.
// This checks that every XPath expression of a rule (objectPath/objpath in
// BREX, @context and @test in Schematron -- extractRuleXPaths(), already
// entity-decoded) parses.
//
// Parser: fontoxpath (XPath 3.1), the same code in the browser and in plain
// Node (scripts/run-prompt-eval.mjs's xpath_valid check), so the app and the
// eval suite always agree. document.createExpression was not used: it is
// XPath 1.0 only and would reject valid DITA Schematron XPath 2.0/3.0
// (`every $r in … satisfies`, `('a','b')`, inline functions) and block
// Accept on correct rules. Consequence, accepted: XPath 2.0+ syntax in a
// BREX objectPath is not reported (only real syntax errors are).
//
// Only syntax errors count (XPST0003). Static errors that are normal in a
// rule fragment -- an undeclared $variable (sch:let), a prefix (xlink:,
// sch:, xs:) or a function this parser doesn't register (matches/3, doc) --
// and dynamic errors (no context item) never make an expression invalid.

const SYNTAX_ERROR = 'XPST0003';

export function isXPathSyntaxValid(expression) {
  try {
    fontoxpath.evaluateXPath(expression, null, null, null, fontoxpath.evaluateXPath.ANY_TYPE, {
      language: fontoxpath.evaluateXPath.XPATH_3_1_LANGUAGE,
    });
    return true;
  } catch (err) {
    return !String(err?.message || '').includes(SYNTAX_ERROR);
  }
}

// The rule's XPath expressions that are not syntactically valid (after
// undoing the XML escapes), in document order, without duplicates.
export function invalidRuleXPaths(ruleXml) {
  const invalid = [];
  for (const expression of extractRuleXPaths(ruleXml)) {
    if (!isXPathSyntaxValid(expression) && !invalid.includes(expression)) invalid.push(expression);
  }
  return invalid;
}

// ═══ 5b. Rule format ═══════════════════════════════════════════════════════

// Consolidation C2, Part 0: what is saved as a rule must contain a rule of
// the project's format. Real case: "Paste rule" with just the text
// //&lt;emphasis&gt; -- well-formed XML, no element at all -- was accepted,
// saved as Draft and could be tested. Checked on well-formed XML only (the
// well-formedness check runs first and reports its own error).
//
// What the top level of the fragment may hold, per format:
//   BREX 4.2/4.1  <structureObjectRule>, <nonContextRule>, or a
//                 <contextRules> block holding at least one structureObjectRule
//   BREX 3.0.1    <objrule>, a <contextrules> block holding at least one
//                 objrule, or the 3.0.1 stand-in for a rule without context:
//                 a comment starting with "nonContextRule" (the XSD has no
//                 nonContextRule element; Generate writes the comment)
//   SCH-DITA      <pattern> or <rule>, with or without a prefix
// Comments are always allowed next to the rule. Loose text and any other
// element are not; a wrapper around a rule (<rules>, a bare
// <structureObjectRuleGroup>) is reported as such, and a rule of another
// format (<sch:pattern> in a BREX project) says which format it belongs to.
// An unknown format is not checked. The backend applies the same check on
// PUT …/approvals/{format} (backend/app/services/rule_format_check.py --
// keep both in sync); the Excel import does not reject with it, but stores a
// rule without legacy wrappers (src/utils/ruleWrappers.js and its backend
// twin), and lint-curated-templates reports anything else.
const RULE_FORMAT_SHAPES = {
  'BREX-4.2': { label: 'BREX 4.2', rules: ['structureObjectRule', 'nonContextRule'], blocks: { contextRules: 'structureObjectRule' }, expected: 'structureObjectRule' },
  'BREX-4.1': { label: 'BREX 4.1', rules: ['structureObjectRule', 'nonContextRule'], blocks: { contextRules: 'structureObjectRule' }, expected: 'structureObjectRule' },
  'BREX-3.0.1': { label: 'BREX 3.0.1', rules: ['objrule'], blocks: { contextrules: 'objrule' }, expected: 'objrule', nonContextComment: true },
  'SCH-DITA': { label: 'Schematron (DITA)', rules: ['pattern', 'rule'], blocks: {}, expected: 'sch:pattern' },
};

// Element names that belong to one format only -- to say which format a
// misplaced rule element belongs to.
const RULE_ELEMENT_FORMAT = {
  structureObjectRule: 'BREX 4.x',
  nonContextRule: 'BREX 4.x',
  contextRules: 'BREX 4.x',
  structureObjectRuleGroup: 'BREX 4.x',
  objrule: 'BREX 3.0.1',
  contextrules: 'BREX 3.0.1',
  structrules: 'BREX 3.0.1',
  pattern: 'Schematron (DITA)',
  rule: 'Schematron (DITA)',
};

const TOP_LEVEL_TOKEN_RE =
  /<!--([\s\S]*?)-->|<\?[\s\S]*?\?>|<!\[CDATA\[([\s\S]*?)\]\]>|<!DOCTYPE[^>]*>|<(\/?)([^\s/>!?]+)(?:\s+[^\s=/>]+\s*=\s*(?:"[^"]*"|'[^']*'))*\s*(\/?)>/g;

const localNameOf = (qname) => qname.replace(/^.*:/, '');

// The top level of a well-formed fragment: elements (with the local names of
// their descendants), comments and loose text.
function scanTopLevel(xml) {
  const top = [];
  let depth = 0;
  let current = null;
  let last = 0;
  let m;
  const pushText = (text) => {
    if (depth === 0 && text.trim()) top.push({ kind: 'text', text: decodeEntities(text.trim()) });
  };
  TOP_LEVEL_TOKEN_RE.lastIndex = 0;
  while ((m = TOP_LEVEL_TOKEN_RE.exec(xml))) {
    pushText(xml.slice(last, m.index));
    last = TOP_LEVEL_TOKEN_RE.lastIndex;
    const [, comment, cdata, closing, name, selfClosing] = m;
    if (comment !== undefined) {
      if (depth === 0) top.push({ kind: 'comment', text: comment.trim() });
    } else if (cdata !== undefined) {
      pushText(cdata);
    } else if (name) {
      if (closing) {
        depth -= 1;
        if (depth === 0) current = null;
      } else if (depth === 0) {
        current = { kind: 'element', name, local: localNameOf(name), descendants: new Set() };
        top.push(current);
        if (!selfClosing) depth += 1;
        else current = null;
      } else {
        current?.descendants.add(localNameOf(name));
        if (!selfClosing) depth += 1;
      }
    }
  }
  pushText(xml.slice(last));
  return top;
}

// { checked, ok, problem: { code, params } | null } for a well-formed rule
// fragment. Codes: rule_format_other_format, rule_format_wrapper,
// rule_format_empty_block, rule_format_foreign, rule_format_missing,
// rule_format_text.
export function checkRuleFormat(ruleXml, format) {
  const shape = RULE_FORMAT_SHAPES[format];
  if (!shape) return { checked: false, ok: true, problem: null };
  const base = { format: shape.label, expected: shape.expected };
  const fail = (code, params = {}) => ({ checked: true, ok: false, problem: { code, params: { ...base, ...params } } });
  const top = scanTopLevel(ruleXml || '');
  let rules = 0;
  for (const node of top) {
    if (node.kind === 'comment') {
      if (shape.nonContextComment && /^nonContextRule\b/.test(node.text)) rules += 1;
      continue;
    }
    if (node.kind !== 'element') continue;
    if (shape.rules.includes(node.local)) {
      rules += 1;
      continue;
    }
    const inner = shape.blocks[node.local];
    if (inner) {
      if (!node.descendants.has(inner)) return fail('rule_format_empty_block', { element: node.name, inner });
      rules += 1;
      continue;
    }
    const otherFormat = RULE_ELEMENT_FORMAT[node.local];
    if (otherFormat && otherFormat !== shape.label && !(shape.label.startsWith('BREX 4') && otherFormat === 'BREX 4.x')) {
      return fail('rule_format_other_format', { element: node.name, otherFormat });
    }
    if (shape.rules.some((r) => node.descendants.has(r))) return fail('rule_format_wrapper', { element: node.name });
    return fail('rule_format_foreign', { element: node.name });
  }
  if (rules === 0) return fail('rule_format_missing');
  const text = top.find((n) => n.kind === 'text');
  if (text) return fail('rule_format_text', { text: text.text.length > 60 ? `${text.text.slice(0, 59)}…` : text.text });
  return { checked: true, ok: true, problem: null };
}

// checkRuleFormat's problem as issues (none when it passes).
