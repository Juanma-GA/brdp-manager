"""Test de reglas DITA: un topic anidado dentro del cuerpo se sube a su sitio
-- generates backend/schema_cards/dita-nesting.json: for each DITA document
type of the rule test (topic, concept, task, reference, troubleshooting),
which topic types each topic element admits as NESTED topics in that type's
own shell (sources/D1.3/schema/technicalContent/xsd/<type>.xsd).

Why a file of its own: the schema cards and the content models resolve DITA
as ONE merged world (generate_schema_cards.py, "merged" mode), and the
per-shell group "info-types" -- which each shell defines differently -- ends
up as the one of the last shell merged: every topic type then nests <task>
and none nests itself (concept.xsd really says concept nests concept). The
rule test's per-type graphs (rule_test_skeletons._dita_graph) leave nested
topics out altogether. This file says the truth per shell.

How a topic type nests, by the DITA 1.3 architecture: the content of topic
type T ends with a group "T-info-types" (defined in TMod.xsd as T | info-types),
and each shell defines "info-types" (and may xs:redefine "T-info-types").
For a shell D: the groups of every *Mod.xsd / *Grp.xsd module, overridden by
the shell's own top-level groups and by the groups inside its xs:redefine
(a self-reference inside a redefine is the module's base group). A group is
resolved to the element names it reaches (xs:element/@ref, following
xs:group/@ref), leaving out maxOccurs="0" (the shells' "no-topic-nesting").
Starting from D, every nested type reached is resolved too.

    cd backend && source .venv/bin/activate
    python scripts/generate_dita_nesting.py
"""
import json
import sys
from pathlib import Path

from lxml import etree

XS = "{http://www.w3.org/2001/XMLSchema}"
_ROOT = Path(__file__).resolve().parents[2]
SOURCES = _ROOT / "sources" / "D1.3" / "schema"
SHELLS_DIR = SOURCES / "technicalContent" / "xsd"
OUT_PATH = Path(__file__).resolve().parents[1] / "schema_cards" / "dita-nesting.json"

# The rule test's DITA topic types (rule_test_skeletons.DITA_DOCUMENT_TYPES
# without the map, which nests no topic).
DOCUMENT_TYPES = ["topic", "concept", "task", "reference", "troubleshooting"]


def _module_groups() -> dict[str, etree._Element]:
    groups: dict[str, etree._Element] = {}
    for path in sorted(SOURCES.glob("*/xsd/*.xsd")):
        if not (path.stem.endswith("Mod") or path.stem.endswith("Grp")):
            continue
        tree = etree.parse(str(path))
        for g in tree.getroot().findall(f"{XS}group"):
            groups.setdefault(g.get("name"), g)
    return groups


def _shell_groups(shell: Path) -> dict[str, etree._Element]:
    root = etree.parse(str(shell)).getroot()
    out: dict[str, etree._Element] = {}
    for g in root.findall(f"{XS}group"):
        out[g.get("name")] = g
    for redefine in root.findall(f"{XS}redefine"):
        for g in redefine.findall(f"{XS}group"):
            out[g.get("name")] = g
    return out


def _resolve(name: str, shell: dict, base: dict, seen: frozenset = frozenset()) -> list[str]:
    """Element names group `name` reaches, in document order, each once."""
    if name in seen:
        group = base.get(name)  # a self-reference inside a redefine
        if group is None or group is shell.get(name):
            return []
    else:
        group = shell.get(name, base.get(name))
    if group is None:
        return []
    out: list[str] = []
    for node in group.iter(f"{XS}element", f"{XS}group"):
        if node is group or node.get("maxOccurs") == "0":
            continue
        ref = node.get("ref")
        if not ref:
            continue
        ref = ref.split(":")[-1]
        names = [ref] if node.tag == f"{XS}element" else _resolve(ref, shell, base, seen | {name})
        for n in names:
            if n not in out:
                out.append(n)
    return out


def build_nesting() -> dict[str, dict[str, list[str]]]:
    base = _module_groups()
    out: dict[str, dict[str, list[str]]] = {}
    for doc_type in DOCUMENT_TYPES:
        shell = _shell_groups(SHELLS_DIR / f"{doc_type}.xsd")
        nesting: dict[str, list[str]] = {}
        frontier = [doc_type]
        while frontier:
            topic = frontier.pop(0)
            if topic in nesting:
                continue
            nested = _resolve(f"{topic}-info-types", shell, base)
            nesting[topic] = nested
            frontier.extend(n for n in nested if n not in nesting)
        out[doc_type] = nesting
    return out


def main() -> None:
    data = {
        "_readme": "Nested topic types per DITA 1.3 shell (technicalContent/xsd/<type>.xsd): "
        "types[<document type>][<topic element>] = the topic types it nests. "
        "Generated by backend/scripts/generate_dita_nesting.py.",
        "types": build_nesting(),
    }
    OUT_PATH.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_PATH}")
    for doc_type, nesting in data["types"].items():
        print(f"  {doc_type}: {nesting}")


if __name__ == "__main__":
    for _stream in (sys.stdout, sys.stderr):  # UTF-8 on any console or pipe, Windows included (Protecciones 1c)
        _stream.reconfigure(encoding="utf-8", errors="backslashreplace")
    main()
